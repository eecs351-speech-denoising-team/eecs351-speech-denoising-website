"""Embed the three exploratory pairs at 16 kHz for the presentation demo.

Writes assets/presentation/clips.js so presentation.html also works from
file:// (browsers block fetch() of local WAVs). Both signals of a pair use the
same polyphase filter as MATLAB resample(x,1,3): 61 taps, Kaiser beta 5.
Samples keep audioread scaling (int16 / 32768) and are stored as float32.
"""
import base64
import json
import pathlib
import wave

import numpy as np
from scipy.signal import resample_poly

ROOT = pathlib.Path(__file__).resolve().parents[1]
CLIPS = [("bus", "p257_004"), ("office", "p257_017"), ("cafe", "p257_009")]


def read_wav(path):
    with wave.open(str(path)) as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2 and w.getframerate() == 48000
        raw = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2")
    return raw.astype(np.float64) / 32768


def encode(x):
    return base64.b64encode(x.astype("<f4").tobytes()).decode("ascii")


def main():
    clips = {}
    for condition, name in CLIPS:
        clean = read_wav(ROOT / "assets/audio/clean" / f"{name}.wav")
        noisy = read_wav(ROOT / "assets/audio/noisy" / f"{name}.wav")
        assert clean.size == noisy.size
        pair = resample_poly(np.column_stack([clean, noisy]), 1, 3, axis=0, window=("kaiser", 5.0))
        clips[condition] = {"file": name, "fs": 16000, "nominalSnrDb": 2.5,
                            "clean": encode(pair[:, 0]), "noisy": encode(pair[:, 1])}
    out = ROOT / "assets/presentation/clips.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by code/build_presentation_clips.py; do not edit.\n"
                   "window.PRESENTATION_CLIPS = " + json.dumps(clips) + ";\n")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
