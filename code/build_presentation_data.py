"""Embed the demo audio and tuning results used by presentation.html.

Writes assets/presentation/clips.js (the three exploratory pairs at 16 kHz) and
assets/presentation/tuning.js (reports/tuning_summary.csv plus the frozen
primary selections), so the page also works from file:// where browsers block
fetch() of local files. Both signals of a pair use the
same polyphase filter as MATLAB resample(x,1,3): 61 taps, Kaiser beta 5.
Samples keep audioread scaling (int16 / 32768) and are stored as float32.
"""
import base64
import csv
import json
import pathlib
import wave

import numpy as np
from scipy.signal import resample_poly

ROOT = pathlib.Path(__file__).resolve().parents[1]
CLIPS = [("bus", "p257_004"), ("office", "p257_017"), ("cafe", "p257_009")]


def read_wav(path):
    with wave.open(str(path)) as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2 and w.getframerate() == 48000
        raw = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2")
    return raw.astype(np.float64) / 32768


def encode(x):
    return base64.b64encode(x.astype("<f4").tobytes()).decode("ascii")


def write_js(path, name, value, source):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"// Generated by code/build_presentation_data.py from {source}; do not edit.\n"
                    f"window.{name} = " + json.dumps(value) + ";\n")
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size / 1e6:.2f} MB)")


def tuning():
    frozen = json.loads((ROOT / "config/frozen_denoisers.json").read_text())
    options = {c["id"]: c.get("options", {}) for c in
               json.loads((ROOT / "config/tuning_candidates.json").read_text())["candidates"]}
    with open(ROOT / "reports/tuning_summary.csv", newline="") as f:
        rows = [{"id": r["candidate"], "method": r["method"], "family": r["family"],
                 "pairs": int(r["pairs"]), "stoi": float(r["mean_stoi"]),
                 "dStoi": float(r["mean_delta_stoi"]), "dSnr": float(r["mean_delta_snr_db"]),
                 "options": options[r["candidate"]]} for r in csv.DictReader(f)]
    return {"status": frozen["status"], "primary": frozen["primary"], "candidates": rows}


def main():
    write_js(ROOT / "assets/presentation/tuning.js", "PRESENTATION_TUNING", tuning(),
             "reports/tuning_summary.csv and config/frozen_denoisers.json")
    clips = {}
    for condition, name in CLIPS:
        clean = read_wav(ROOT / "assets/audio/clean" / f"{name}.wav")
        noisy = read_wav(ROOT / "assets/audio/noisy" / f"{name}.wav")
        assert clean.size == noisy.size
        pair = resample_poly(np.column_stack([clean, noisy]), 1, 3, axis=0, window=("kaiser", 5.0))
        clips[condition] = {"file": name, "fs": 16000, "nominalSnrDb": 2.5,
                            "clean": encode(pair[:, 0]), "noisy": encode(pair[:, 1])}
    write_js(ROOT / "assets/presentation/clips.js", "PRESENTATION_CLIPS", clips, "assets/audio")


if __name__ == "__main__":
    main()
